/**
 * Normalizes text for reliable matching (collapses multiple whitespace/newlines)
 */
function normalizeText(text) {
  return text ? text.replace(/\s+/g, " ").trim() : "";
}

/**
 * Cleans drop-cap text (e.g., "T angerang" -> "Tangerang", "Y ogyakarta" -> "Yogyakarta")
 */
function cleanDropCap(text) {
  return text ? text.replace(/^([A-Z])\s+([a-z]+)/, "$1$2") : "";
}

// Build fast lookup maps
const enToIdMap = new Map();
const idToEnMap = new Map();

dictionary.forEach((item) => {
  const normEn = normalizeText(item.en);
  const normId = normalizeText(item.id);
  if (normEn && normId && normEn !== normId) {
    if (!enToIdMap.has(normEn)) {
      enToIdMap.set(normEn, item.id);
    }
    if (!idToEnMap.has(normId)) {
      idToEnMap.set(normId, item.en);
    }
  }
});

/**
 * Returns current preferred language. Default is 'en'.
 */
export function getPreferredLanguage() {
  if (typeof window === "undefined") return "en";
  try {
    return localStorage.getItem("preferred_lang") || "en";
  } catch (e) {
    return "en";
  }
}

/**
 * Translates a single text string based on target language
 */
export function translateText(text, targetLang) {
  if (!text) return text;
  const normalized = normalizeText(text);

  if (targetLang === "id") {
    if (enToIdMap.has(normalized)) {
      const match = enToIdMap.get(normalized);
      const lead = text.match(/^\s*/)?.[0] || "";
      const trail = text.match(/\s*$/)?.[0] || "";
      return lead + match + trail;
    }
  } else if (targetLang === "en") {
    if (idToEnMap.has(normalized)) {
      const match = idToEnMap.get(normalized);
      const lead = text.match(/^\s*/)?.[0] || "";
      const trail = text.match(/\s*$/)?.[0] || "";
      return lead + match + trail;
    }
  }
  return text;
}

