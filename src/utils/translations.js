/**
 * Traverses DOM text nodes and replaces text according to target language.
 * Completely preserves DOM structure, attributes, styles, and listeners.
 */
export function applyLanguage(targetLang = "en") {
  if (typeof document === "undefined") return;

  document.documentElement.lang = targetLang;

  // Pass 1: Translate compound elements with inner HTML tags
  const matchedCompoundElements = new Set();
  const candidateElements = document.querySelectorAll(
    "p, h1, h2, h3, h4, div, span, a"
  );

  candidateElements.forEach((el) => {
    const rawText = normalizeText(el.textContent);
    const text = cleanDropCap(rawText);

    for (const item of compoundTranslations) {
      const normEn = normalizeText(item.enText);
      const cleanEn = cleanDropCap(normEn);
      const normId = normalizeText(item.idText);
      const cleanId = cleanDropCap(normId);

      if (
        targetLang === "id" &&
        (rawText === normEn || text === cleanEn || text === normEn)
      ) {
        if (!el.getAttribute("data-orig-html")) {
          el.setAttribute("data-orig-html", el.innerHTML);
        }
        el.innerHTML = item.idHtml;
        matchedCompoundElements.add(el);
        break;
      } else if (
        targetLang === "en" &&
        (rawText === normId || text === cleanId || text === normId)
      ) {
        const origHtml = el.getAttribute("data-orig-html");
        if (origHtml) {
          el.innerHTML = origHtml;
        } else {
          el.innerHTML = item.enHtml;
        }
        matchedCompoundElements.add(el);
        break;
      }
    }
  });

  // Pass 2: Walk remaining text nodes
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        if (!node.nodeValue || !node.nodeValue.trim()) {
          return NodeFilter.FILTER_REJECT;
        }
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;

        // Skip compound elements already translated in Pass 1
        let p = parent;
        while (p && p !== document.body) {
          if (matchedCompoundElements.has(p)) {
            return NodeFilter.FILTER_REJECT;
          }
          p = p.parentElement;
        }

        // Skip non-translatable tags and protected brand elements
        const tagName = parent.tagName.toLowerCase();
        if (
          ["script", "style", "noscript", "svg", "code", "pre"].includes(tagName) ||
          parent.closest('[translate="no"]') ||
          parent.closest(".notranslate") ||
          parent.closest("#nav-logo-white") ||
          parent.closest("#nav-logo-color") ||
          parent.closest("#nav-title")
        ) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      },
    }
  );

  const textNodes = [];
  while (walker.nextNode()) {
    textNodes.push(walker.currentNode);
  }

  textNodes.forEach((node) => {
    const raw = node.nodeValue;
    // @ts-ignore
    if (!node.__orig_text && targetLang === "id") {
      // @ts-ignore
      node.__orig_text = raw;
    }

    if (targetLang === "en") {
      // @ts-ignore
      if (node.__orig_text) {
        // @ts-ignore
        node.nodeValue = node.__orig_text;
        return;
      }
    }

    const translated = translateText(raw, targetLang);
    if (translated !== raw) {
      node.nodeValue = translated;
    }
  });

  // Also translate common button titles and aria-labels if applicable
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const title = el.getAttribute("title");
    if (title) el.setAttribute("title", translateText(title, targetLang));
  });

  // Update active UI switchers across the document
  updateSwitcherUI(targetLang);

  // Dispatch global event for any dynamic component
  window.dispatchEvent(
    new CustomEvent("languageChanged", { detail: { lang: targetLang } })
  );
}

/**
 * Updates visual state of EN | ID buttons on navbar/mobile menu
 */
export function updateSwitcherUI(lang) {
  if (typeof document === "undefined") return;

  const buttons = document.querySelectorAll("[data-lang-btn]");
  buttons.forEach((btn) => {
    const btnLang = btn.getAttribute("data-lang-btn");
    const isActive = btnLang === lang;
    btn.setAttribute("data-active", isActive ? "true" : "false");
    btn.setAttribute("aria-pressed", isActive ? "true" : "false");
  });

  // Trigger navbar scroll styling update so colors stay harmonious
  if (typeof window.updateNavLanguageStyles === "function") {
    window.updateNavLanguageStyles();
  }
}

/**
 * Sets language preference and triggers DOM translation
 */
export function setLanguage(lang) {
  if (lang !== "en" && lang !== "id") return;
  try {
    localStorage.setItem("preferred_lang", lang);
  } catch (e) {}
  applyLanguage(lang);
}

/**
 * Initializes language listeners on page load
 */
export function initLanguageSystem() {
  if (typeof window === "undefined" || window.__dpsa_i18n_initialized) {
    // If already initialized on SPA navigation, just re-apply
    const current = getPreferredLanguage();
    applyLanguage(current);
    return;
  }
  window.__dpsa_i18n_initialized = true;

  const current = getPreferredLanguage();

  // Bind click on all language switcher buttons (using delegated listener)
  document.addEventListener("click", (e) => {
    const target = e.target;
    if (!(target instanceof Element)) return;
    const btn = target.closest("[data-lang-btn]");
    if (btn) {
      e.preventDefault();
      const targetLang = btn.getAttribute("data-lang-btn");
      if (targetLang) {
        setLanguage(targetLang);
      }
    }
  });

  // Initial translation apply
  applyLanguage(current);
}
